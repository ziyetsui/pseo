import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const postcss = createRequire(require.resolve('next/package.json'))('postcss');
const source = await readFile(new URL('../../docs/wireframes/proto-continuous-peek.html', import.meta.url), 'utf8');
const styles = [...source.matchAll(/<style(?:\s[^>]*)?>([\s\S]*?)<\/style>/g)];
const root = postcss.parse(styles[0][1] + '\n' + styles.find(item => item[0].startsWith('<style id="linear-dark-theme"'))[1]);
const scope = ':where(.prototype-magnetic)';
root.walkComments(comment => comment.remove());
root.walkDecls('src', declaration => { declaration.value = declaration.value.replaceAll('https://cdn.jsdelivr.net/npm/@fontsource-variable/inter@5/files/inter-latin-wght-normal.woff2', '/fonts/inter-latin-wght-normal.woff2'); });
root.walkRules(rule => {
  if (rule.parent.type === 'atrule' && /keyframes$/.test(rule.parent.name)) return;
  rule.selectors = rule.selectors.map(selector => {
    let value = selector.replaceAll(':root[data-theme="linear-dark"]', scope).replaceAll(':root', scope).replace(/(^|[\s>+~])(?:html|body)(?=[:.\s>+~#\[]|$)/g, `$1${scope}`);
    if (!value.includes(scope)) value = `${scope} ${value}`;
    return value;
  });
});
await writeFile(new URL('../src/styles/magnetic.css', import.meta.url), '/* Generated by scripts/extract-magnetic.mjs; Magnetic v2 + default Linear dark. */\n' + root.toString());
await writeFile(new URL('../evidence/magnetic-reference.json', import.meta.url), JSON.stringify({ source:'docs/wireframes/proto-continuous-peek.html', url:'http://127.0.0.1:8766/proto-continuous-peek.html?v=2', variant:'variants[1] / vMagnet', sha256:createHash('sha256').update(source).digest('hex'), theme:'linear-dark', overrides:['No hero signature','No copy buttons','Generate image / Generate video / Generate → actual prompt L4','No prototype picker or theme toggle'] },null,2)+'\n');
